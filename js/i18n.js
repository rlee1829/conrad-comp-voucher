  function t(s) {
    if (lang !== 'en' || s == null) return s;
    var v = EN[s];
    return v == null ? s : v;
  }
  // A handful of Korean words carry two unrelated meanings depending on where they show up
  // (e.g. "취소" is both the generic modal "Cancel" button and the voucher "Void" action/status).
  // The dict below resolves '취소' to the more specific "Void" — t2 lets call sites that need the
  // generic modal-dismiss meaning override it explicitly instead of relying on exact-string lookup.
  function t2(ko, en) { return lang === 'en' ? en : ko; }

  function getLang() { return lang; }

  function applyStatic(root) {
    var scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    scope.querySelectorAll('[data-i18n-ph]').forEach(function (el) { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  }

  function refreshApp() {
    if (!CompApp.router) return;
    CompApp.router.renderCounts();
    if (CompApp.router.renderTitle) CompApp.router.renderTitle();
    if (CompApp.state.view === 'issue') { if (CompApp.viewIssue && CompApp.viewIssue.relabel) CompApp.viewIssue.relabel(); }
    else CompApp.router.refresh();
    if (CompApp.operator && CompApp.operator.renderOpCard) CompApp.operator.renderOpCard();
  }

  function setLang(l) {
    lang = (l === 'en') ? 'en' : 'ko';
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
    document.documentElement.lang = lang;
    document.querySelectorAll('#langSwitch button').forEach(function (b) { b.setAttribute('aria-pressed', b.dataset.lang === lang ? 'true' : 'false'); });
    applyStatic();
    refreshApp();
  }

  function wire() {
    var sw = document.getElementById('langSwitch'); if (!sw) return;
    sw.querySelectorAll('button[data-lang]').forEach(function (b) { b.setAttribute('aria-pressed', b.dataset.lang === lang ? 'true' : 'false'); });
    sw.addEventListener('click', function (e) { var b = e.target.closest('button[data-lang]'); if (!b) return; setLang(b.dataset.lang); });
  }

  function init() { document.documentElement.lang = lang; wire(); applyStatic(); }

  return { t: t, t2: t2, getLang: getLang, setLang: setLang, applyStatic: applyStatic, init: init };
